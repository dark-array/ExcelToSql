using System.Globalization;
using System.Text;
using ExcelToSql.Models;

namespace ExcelToSql.Services;

public sealed class OracleSqlDialect : ISqlDialect
{
    public string DisplayName => "Oracle";
    public int MaxIdentifierLength => 128;
    public int InsertBatchSize => 1;
    public string CreateTableSuffix => ");";
    public string ScriptFooter => string.Empty;

    public string QuoteIdentifier(string name) => "\"" + name.Replace("\"", "\"\"") + "\"";

    public string ColumnDeclaration(ColumnDefinition column, bool isIdentity)
    {
        var ident = QuoteIdentifier(column.SqlName);
        if (isIdentity)
            return $"{ident} NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY";

        var type = column.DataType switch
        {
            LogicalType.Integer => "NUMBER(10)",
            LogicalType.BigInteger => "NUMBER(19)",
            LogicalType.Decimal => $"NUMBER({Math.Clamp(column.Precision, 1, 38)},{Math.Clamp(column.Scale, 0, 10)})",
            LogicalType.Boolean => "NUMBER(1)",
            LogicalType.Date => "DATE",
            LogicalType.DateTime => "TIMESTAMP",
            LogicalType.LongText => "CLOB",
            _ => $"VARCHAR2({Math.Clamp(column.Length <= 0 ? 255 : column.Length, 1, 4000)})"
        };

        return $"{ident} {type}";
    }

    public string FormatValue(string? raw, LogicalType type, bool trimWhitespace)
    {
        if (raw is null)
            return "NULL";

        var value = trimWhitespace ? raw.Trim() : raw;
        if (value.Length == 0)
            return "NULL";

        switch (type)
        {
            case LogicalType.Integer:
            case LogicalType.BigInteger:
                return TypeInference.IsInteger(value) ? value.Trim() : QuoteString(value);
            case LogicalType.Decimal:
                return TypeInference.TryParseDecimal(value, out var number)
                    ? number.ToString(CultureInfo.InvariantCulture)
                    : QuoteString(value);
            case LogicalType.Boolean:
                var flag = TypeInference.ParseBoolean(value);
                return flag is null ? QuoteString(value) : (flag.Value ? "1" : "0");
            case LogicalType.Date:
                return TypeInference.TryParseDateTime(value, out var date)
                    ? $"TO_DATE('{date:yyyy-MM-dd}', 'YYYY-MM-DD')"
                    : QuoteString(value);
            case LogicalType.DateTime:
                return TypeInference.TryParseDateTime(value, out var dt)
                    ? $"TO_TIMESTAMP('{dt:yyyy-MM-dd HH:mm:ss}', 'YYYY-MM-DD HH24:MI:SS')"
                    : QuoteString(value);
            default:
                return QuoteString(value);
        }
    }

    public string BeginDmlBlock(string quotedTable, bool hasIdentity) => "BEGIN";

    public string EndDmlBlock(string quotedTable, bool hasIdentity)
        => "  COMMIT;" + Environment.NewLine + "END;" + Environment.NewLine + "/";

    public string ScriptHeader(string fileName)
    {
        var sb = new StringBuilder();
        sb.AppendLine("-- ExcelToSql");
        sb.AppendLine($"-- Archivo : {fileName}");
        sb.AppendLine("-- Motor   : Oracle");
        sb.AppendLine($"-- Generado: {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
        sb.AppendLine("-- IDENTITY se crea GENERATED BY DEFAULT para conservar los valores originales.");
        sb.AppendLine("WHENEVER SQLERROR EXIT SQL.SQLCODE;");
        return sb.ToString();
    }

    private static string QuoteString(string value) => "'" + value.Replace("'", "''") + "'";
}
